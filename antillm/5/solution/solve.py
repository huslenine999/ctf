#!/usr/bin/env python3

EXPECTED = [
    0xf1,0xa3,0xcc,0xd9,0xf3,0x0c,0x18,0x21,0x5c,0x4b,0xe6,0x8c,0x5e,0xbd,0xba,0x60,
    0xd6,0x50,0xc4,0x40,0xe1,0x0e,0x93,0xa0,0x5b,0x53,0x1e,0x6c,0x7f,0x1f,0x35,0x95,
]


def ror8(x, n):
    n &= 7
    if n == 0:
        return x
    return ((x >> n) | (x << (8 - n))) & 0xFF


def main():
    out = []

    for pos, value in enumerate(EXPECTED):
        x = ror8(value, pos)
        x ^= 0xA7
        x = (x - ((pos * 17) & 0xFF)) & 0xFF
        out.append(x)

    print(bytes(out).decode())


if __name__ == "__main__":
    main()
