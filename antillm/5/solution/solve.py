#!/usr/bin/env python3

EXPECTED = [
    0xf1,0x85,0x0b,0xe6,0x81,0x8d,0x1d,0xb8,0x57,0xba,0xfe,0xc5,0xf9,0xbc,0xf1,0xea,
    0xc8,0x44,0xc0,0x70,0xa1,0x8e,0x1f,0xa0,0xab,0x79,0x22,0xc4,0x3e,0x35,0x2e,0x95,
]


def ror8(x, n):
    n &= 7
    if n == 0:
        return x
    return ((x >> n) | (x << (8 - n))) & 0xFF


def main():
    out = []

    for pos, value in enumerate(EXPECTED):
        x = ror8(value, pos)
        x ^= 0xA7
        x = (x - ((pos * 17) & 0xFF)) & 0xFF
        out.append(x)

    print(bytes(out).decode())


if __name__ == "__main__":
    main()
